#!/usr/bin/env python3
"""Generate the 56px home-tile icons used by the Tile theme.

Rasterizes Lucide SVGs (with a thinner stroke than Lucide's default, to match the
stock Xteink home tiles) into 2-bpp arrays: row-major, MSB-first, 4 pixels per byte,
0 = paper, 1 = light gray, 2 = dark gray, 3 = ink (the same levels as the 2-bit
fonts), rowBytes = size / 4. The arrays are NOT pre-rotated; TileTheme plots them
pixel by pixel in Portrait, black for 2..3 in the B/W pass and the grays in the
anti-aliasing overlay pass.

Usage:
    python3 scripts/gen_tile_icons.py \
        --svgdir freeink-sdk/libs/assets/Icons/lucide/icons \
        --out src/components/themes/tile/TileIcons.h

Requires: cairosvg (needs libcairo) and Pillow.
"""

import argparse
import io
import os
import re

import cairosvg
from PIL import Image

SIZE = 56
STROKE = "1.6"
THRESHOLD = 128

# alias -> lucide icon name, or inline SVG body for composed icons.
ICONS = {
    # Stock's folder has the closed-folder crease line, and its Read tile a bookmark.
    "folder": "folder-closed",
    "bookmark": "bookmark",
    "library": "library",
    "wifi": "wifi",
    "blocks": "blocks",
    "book": "book-open",
    # Stock-style settings glyph: a hexagon nut with a hole.
    "settings": '<path d="M21 16V8a2 2 0 0 0-1-1.73l-7-4a2 2 0 0 0-2 0l-7 4A2 2 0 0 0 3 8v8a2 2 0 0 0 1 '
    '1.73l7 4a2 2 0 0 0 2 0l7-4A2 2 0 0 0 21 16z"/><circle cx="12" cy="12" r="3"/>',
}

SVG_WRAPPER = (
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
    'stroke="#000" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
)


def load_svg(svgdir, source):
    if source.lstrip().startswith("<"):
        return SVG_WRAPPER.format(stroke=STROKE, body=source)
    with open(os.path.join(svgdir, source + ".svg"), encoding="utf-8") as fh:
        svg = fh.read()
    svg = re.sub(r'stroke-width="[^"]*"', f'stroke-width="{STROKE}"', svg)
    return svg.replace('stroke="currentColor"', 'stroke="#000"')


def rasterize(svg):
    png = cairosvg.svg2png(bytestring=svg.encode("utf-8"), output_width=SIZE, output_height=SIZE)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    bg.paste(img, mask=img.split()[3])
    return bg.convert("L")


def pack(img):
    pix = img.load()
    row_bytes = (SIZE + 3) // 4
    data = []
    for y in range(SIZE):
        for b in range(row_bytes):
            byte = 0
            for slot in range(4):
                x = b * 4 + slot
                level = 3 - (pix[x, y] >> 6) if x < SIZE else 0  # 0..3, darker = higher
                byte |= level << (6 - slot * 2)
            data.append(byte)
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--svgdir", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    lines = [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "// Generated by scripts/gen_tile_icons.py from Lucide SVGs. Do not edit.",
        f"// {SIZE}x{SIZE}, 2 bpp, row-major, MSB-first, 0 = paper .. 3 = ink. Not pre-rotated.",
        "namespace TileIcons {",
        f"constexpr int SIZE = {SIZE};",
    ]
    for alias, source in ICONS.items():
        data = pack(rasterize(load_svg(args.svgdir, source)))
        lines.append(f"static const uint8_t {alias}[] = {{")
        for i in range(0, len(data), 15):
            lines.append("    " + ", ".join(f"0x{v:02X}" for v in data[i : i + 15]) + ",")
        lines.append("};")
    lines.append("}  // namespace TileIcons")
    lines.append("")
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    main()
